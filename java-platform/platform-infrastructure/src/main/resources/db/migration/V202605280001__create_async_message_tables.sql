-- spec05: 创建异步消息 Outbox、Inbox 和死信表
CREATE TABLE `outbox_event` (
    `id`              VARCHAR(36)  NOT NULL COMMENT 'UUIDv7 Outbox 记录 ID',
    `event_id`        VARCHAR(36)  NOT NULL COMMENT 'MQ 事件 ID',
    `aggregate_type`  VARCHAR(32)  NOT NULL COMMENT '聚合类型',
    `aggregate_id`    VARCHAR(36)  NOT NULL COMMENT '聚合 ID',
    `task_id`         VARCHAR(36)  NOT NULL COMMENT '任务 ID',
    `task_type`       VARCHAR(64)  NOT NULL COMMENT '任务类型',
    `attempt_no`      INT          NOT NULL COMMENT '执行尝试序号',
    `event_type`      VARCHAR(128) NOT NULL COMMENT '命令事件类型',
    `routing_key`     VARCHAR(128) NOT NULL COMMENT 'RabbitMQ 路由键',
    `payload`         JSON         NOT NULL COMMENT '命令 payload',
    `status`          VARCHAR(32)  NOT NULL COMMENT '投递状态',
    `retry_count`     INT          NOT NULL DEFAULT 0 COMMENT '投递次数',
    `max_retry_count` INT          NOT NULL DEFAULT 5 COMMENT '最大投递次数',
    `next_retry_at`   DATETIME(3)  DEFAULT NULL COMMENT '下次投递时间',
    `last_error`      VARCHAR(500) DEFAULT NULL COMMENT '脱敏失败原因',
    `trace_id`        VARCHAR(64)  NOT NULL COMMENT '链路追踪 ID',
    `created_at`      DATETIME(3)  NOT NULL COMMENT '创建时间',
    `updated_at`      DATETIME(3)  NOT NULL COMMENT '更新时间',
    `delivered_at`    DATETIME(3)  DEFAULT NULL COMMENT '投递成功时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_outbox_event_event_id` (`event_id`),
    UNIQUE KEY `uk_outbox_event_task_attempt_event` (`task_id`, `attempt_no`, `event_type`),
    INDEX `idx_outbox_event_status_next_retry` (`status`, `next_retry_at`),
    INDEX `idx_outbox_event_task_id` (`task_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='任务命令 Outbox 事件表';

CREATE TABLE `inbox_event` (
    `id`              VARCHAR(36)  NOT NULL COMMENT 'UUIDv7 Inbox 记录 ID',
    `event_id`        VARCHAR(36)  NOT NULL COMMENT 'Worker 事件 ID',
    `event_type`      VARCHAR(128) NOT NULL COMMENT 'Worker 事件类型',
    `task_id`         VARCHAR(36)  NOT NULL COMMENT '任务 ID',
    `task_type`       VARCHAR(64)  NOT NULL COMMENT '任务类型',
    `attempt_no`      INT          NOT NULL COMMENT '执行尝试序号',
    `feedback_type`   VARCHAR(32)  NOT NULL COMMENT '反馈类型',
    `status`          VARCHAR(32)  NOT NULL COMMENT '消费状态',
    `payload_hash`    CHAR(64)     NOT NULL COMMENT 'payload SHA-256',
    `payload_summary` JSON         DEFAULT NULL COMMENT '脱敏摘要 JSON',
    `retry_count`     INT          NOT NULL DEFAULT 0 COMMENT '消费重试次数',
    `max_retry_count` INT          NOT NULL DEFAULT 5 COMMENT '最大消费次数',
    `last_error`      VARCHAR(500) DEFAULT NULL COMMENT '脱敏失败原因',
    `trace_id`        VARCHAR(64)  NOT NULL COMMENT '链路追踪 ID',
    `received_at`     DATETIME(3)  NOT NULL COMMENT '首次收到时间',
    `processed_at`    DATETIME(3)  DEFAULT NULL COMMENT '处理完成时间',
    `created_at`      DATETIME(3)  NOT NULL COMMENT '创建时间',
    `updated_at`      DATETIME(3)  NOT NULL COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_inbox_event_event_id` (`event_id`),
    INDEX `idx_inbox_event_task_attempt` (`task_id`, `attempt_no`),
    INDEX `idx_inbox_event_status` (`status`),
    INDEX `idx_inbox_event_trace_id` (`trace_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Worker 反馈 Inbox 事件表';

CREATE TABLE `async_dead_letter` (
    `id`             VARCHAR(36)  NOT NULL COMMENT 'UUIDv7 死信记录 ID',
    `source_type`    VARCHAR(32)  NOT NULL COMMENT '来源类型',
    `source_id`      VARCHAR(128) NOT NULL COMMENT '来源记录 ID',
    `task_id`        VARCHAR(36)  NOT NULL COMMENT '任务 ID',
    `task_type`      VARCHAR(64)  DEFAULT NULL COMMENT '任务类型',
    `attempt_no`     INT          NOT NULL COMMENT '执行尝试序号',
    `failure_stage`  VARCHAR(128) DEFAULT NULL COMMENT '失败阶段',
    `failure_reason` VARCHAR(500) NOT NULL COMMENT '脱敏失败原因',
    `retryable`      TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否可人工重试',
    `manual_handled` TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否人工处理',
    `trace_id`       VARCHAR(64)  NOT NULL COMMENT '链路追踪 ID',
    `created_at`     DATETIME(3)  NOT NULL COMMENT '创建时间',
    `updated_at`     DATETIME(3)  NOT NULL COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_async_dead_letter_source` (`source_type`, `source_id`),
    INDEX `idx_async_dead_letter_task_id` (`task_id`),
    INDEX `idx_async_dead_letter_handled_created` (`manual_handled`, `created_at`),
    INDEX `idx_async_dead_letter_source_type` (`source_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='异步协作死信记录表';
